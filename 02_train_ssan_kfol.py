"""
Dual-branch spectral-spatial neural network training script with ablation options.

This script trains a TensorFlow 1.x dual-branch model for binary geochemical
prediction. The spectral branch uses a bidirectional GRU to model the ordered
feature channels at the center pixel of each patch, while the spatial branch uses
a CNN to learn spatial patterns from the full image patch. Optional spectral
attention, spatial attention, causal feature ordering, geological constraint
weighting, and branch-level ablation settings can be enabled or disabled through
command-line arguments.

The script loads preprocessed `.npy` datasets generated by the preprocessing
script, combines the training and validation samples, and performs stratified
K-fold cross-validation. For each fold, the best model checkpoint is saved based
on validation F1-score. After training, the script ensembles the saved fold
models, evaluates them on the original validation set, and optionally extracts
spectral and spatial attention maps for known deposit locations.

Required input files:

* `X_train.npy`, `y_train.npy`
* `X_val.npy`, `y_val.npy`
* `coords_train.npy`, `coords_val.npy` if geological constraints or attention
  extraction are required
* `geological_weights.npy` if `--use_geo` is enabled
* `causal_feature_order_custom.npy` if `--use_causal` is enabled
* `Au_deposits0.tif` if attention maps for deposit locations are required

Example usage:

* Train the full model with default settings:
  `python train_model.py`

* Disable geological constraints:
  `python train_model.py --no_geo`

* Train only the spectral branch:
  `python train_model.py --branch spectral`

* Disable spectral and spatial attention:
  `python train_model.py --no_spectral_att --no_spatial_att`

Main outputs:

* Best fold checkpoints saved under `D:\SSAN_Checkpoints`
* `spectral_attention_on_deposits.npy`
* `spatial_attention_on_deposits.npy`
* `spectral_attention_heatmap.png`
* `spatial_attention_subplots.png`
* Ensemble evaluation metrics printed to the console
  """

